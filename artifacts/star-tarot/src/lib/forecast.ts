export function getYearlyOverview(): string {
  const year = new Date().getFullYear();
  const overviews = [
    `${year}年的生活提醒：先選一兩件最值得投入的事，再安排工作、關係與收支。每隔一段時間回顧一次，保留有效的做法，調整讓你一直疲憊的安排。`,
    `${year}年的生活提醒：面對變動時，先守住必要的生活安排，再考慮新的嘗試。重要決定可以多留一點了解與討論的時間，不必把所有事情都擠在同一個月完成。`,
  ];
  return overviews[year % overviews.length];
}

