export function getCompatibility(m1: number, d1: number, m2: number, d2: number) {
  const base  = (m1 * d1 + m2 * d2) % 40;
  const score = 60 + base;

  let summary = "";
  if (score >= 95) summary = "相處提醒：珍惜默契，也談清楚彼此的期待";
  else if (score >= 90) summary = "相處提醒：有共同興趣時，也保留各自的生活";
  else if (score >= 85) summary = "相處提醒：願意理解彼此，也要直接說出需要";
  else if (score >= 80) summary = "相處提醒：把吸引力放進日常，看彼此能否穩定回應";
  else if (score >= 75) summary = "相處提醒：發揮各自長處，分工也需要商量";
  else if (score >= 70) summary = "相處提醒：遇到不同意見，先了解原因再討論";
  else summary = "相處提醒：差異需要溝通，不必勉強自己迎合";

  const sun1  = getZodiac(m1, d1);
  const sun2  = getZodiac(m2, d2);

  // Use sign indices to diversify content selection
  const signIdx1  = ["牡羊座","金牛座","雙子座","巨蟹座","獅子座","處女座",
    "天秤座","天蠍座","射手座","魔羯座","水瓶座","雙魚座"].indexOf(sun1);
  const signIdx2  = ["牡羊座","金牛座","雙子座","巨蟹座","獅子座","處女座",
    "天秤座","天蠍座","射手座","魔羯座","水瓶座","雙魚座"].indexOf(sun2);

  const blindIdx   = ((signIdx1 >= 0 ? signIdx1 : m1) + (signIdx2 >= 0 ? signIdx2 : m2)) % BLIND_SPOTS.length;
  const powerIdx   = ((m1 * 3 + d2) + (m2 + d1 * 2)) % SUPER_POWERS.length;
  const yearlyIdx  = (m1 + m2 + d1 + d2) % YEARLY_RESONANCE.length;

  const crossNote = `（太陽：${sun1} × ${sun2}）`;

  return {
    score,
    summary,
    crossNote,
    sections: {
      blindSpots: BLIND_SPOTS[blindIdx],
      superPowers: SUPER_POWERS[powerIdx],
      yearlyResonance: YEARLY_RESONANCE[yearlyIdx],
    }
  };
}
